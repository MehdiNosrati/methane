import type { GeneratedFile, NormalizedComponentModel } from '../types.js';

const BANNER = '// Generated by @methane-ui/wrapper-codegen. Do not edit by hand.';

function emitSveltePropsInterface(model: NormalizedComponentModel): string {
  const propLines = model.props.map(
    (p) => `  /** ${p.description || p.name} */\n  ${p.name}?: ${p.type} | undefined;`,
  );
  const eventLines = model.events.map(
    (ev) =>
      `  /** ${ev.description || ev.name} */\n  ${JSON.stringify(ev.sveltePropName)}?: ((event: CustomEvent<${ev.detailType}>) => void) | undefined;`,
  );

  return `export interface ${model.className}Props {
${[...propLines, ...eventLines, '  children?: unknown;'].join('\n')}
}`;
}

function emitSvelteWrapperDescriptor(model: NormalizedComponentModel): string {
  const bindables = model.bindableProps.map((b) => JSON.stringify(b)).join(', ');
  return `export interface ${model.className}SvelteWrapper {
  readonly name: ${JSON.stringify(model.className)};
  readonly tagName: ${JSON.stringify(model.tagName)};
  readonly bindableProps: ReadonlyArray<'value' | 'checked' | 'open'>;
  readonly __props?: ${model.className}Props;
}

export const ${model.className}: ${model.className}SvelteWrapper = {
  name: ${JSON.stringify(model.className)},
  tagName: ${JSON.stringify(model.tagName)},
  bindableProps: [${bindables}],
};`;
}

function emitSvelteComponentModule(model: NormalizedComponentModel): string {
  return `${BANNER}
import type {} from 'svelte/elements';

${emitSveltePropsInterface(model)}

${emitSvelteWrapperDescriptor(model)}

declare module 'svelte/elements' {
  export interface SvelteHTMLElements {
    ${JSON.stringify(model.tagName)}: ${model.className}Props;
  }
}
`;
}

function addEventStatements(
  map: Map<string, string[]>,
  eventNames: ReadonlyArray<string>,
  statement: string,
): void {
  for (const eventName of eventNames) {
    const existing = map.get(eventName);
    if (existing) {
      existing.push(statement);
    } else {
      map.set(eventName, [statement]);
    }
  }
}

function emitSvelte5ComponentSource(model: NormalizedComponentModel): string {
  const bindableDecls: string[] = [];
  const restEntries: string[] = [];

  for (const bindProp of model.bindableProps) {
    const prop = model.props.find((p) => p.name === bindProp);
    const defaultExpr = prop?.defaultValue ?? 'undefined';
    bindableDecls.push(`  ${bindProp} = $bindable(${defaultExpr})`);
  }
  bindableDecls.push('  children');
  bindableDecls.push('  ...rest');

  for (const bindProp of model.bindableProps) {
    restEntries.push(`${bindProp}={${bindProp}}`);
  }

  const handlersByEvent = new Map<string, string[]>();
  if (model.bindableProps.includes('value')) {
    addEventStatements(
      handlersByEvent,
      ['input', 'change', 'mth-input', 'mth-change', 'mth-select'],
      'const nextValue = (e as CustomEvent<{ value?: typeof value } | undefined>).detail?.value ?? (e.currentTarget as HTMLElement & { value?: typeof value }).value; if (nextValue !== undefined) value = nextValue;',
    );
  }
  if (model.bindableProps.includes('checked')) {
    addEventStatements(
      handlersByEvent,
      ['change', 'mth-change', 'mth-input'],
      'const nextChecked = (e as CustomEvent<{ checked?: boolean } | undefined>).detail?.checked ?? (e.currentTarget as HTMLElement & { checked?: boolean }).checked; if (typeof nextChecked === "boolean") checked = nextChecked;',
    );
  }
  if (model.bindableProps.includes('open')) {
    addEventStatements(handlersByEvent, ['mth-open'], 'open = true;');
    addEventStatements(handlersByEvent, ['mth-close'], 'open = false;');
  }

  const syncHandlers = [...handlersByEvent.entries()].map(
    ([eventName, statements]) =>
      `on${eventName}={(e: Event) => { ${statements.join(' ')} (rest as Record<string, ((ev: Event) => void) | undefined>)[${JSON.stringify(`on${eventName}`)}]?.(e); }}`,
  );

  const attrs = [...restEntries, '{...rest}', ...syncHandlers].join(' ');

  return `<script lang="ts">
  import type { ${model.className}Props } from '../components/${model.tagName}.js';

  let {
${bindableDecls.join(',\n')}
  }: ${model.className}Props = $props();
</script>

<${model.tagName} ${attrs}>
  {@render children?.()}
</${model.tagName}>
`;
}

export function generateSvelteFiles(
  models: ReadonlyArray<NormalizedComponentModel>,
): GeneratedFile[] {
  const files: GeneratedFile[] = [];

  for (const model of models) {
    files.push({
      path: `generated/components/${model.tagName}.ts`,
      content: emitSvelteComponentModule(model),
    });
    files.push({
      path: `generated/svelte/${model.className}.svelte`,
      content: emitSvelte5ComponentSource(model),
    });
  }

  const componentExports = models
    .map((m) => `export * from './components/${m.tagName}.js';`)
    .join('\n');

  files.push({
    path: 'generated/index.ts',
    content: `${BANNER}\n${componentExports}\n`,
  });

  return files;
}
