import type { GeneratedFile, NormalizedComponentModel } from '../types.js';

const BANNER = '// Generated by @methane-ui/wrapper-codegen. Do not edit by hand.';

function emitVuePropsInterface(model: NormalizedComponentModel): string {
  const propLines = model.props.map(
    (p) => `  /** ${p.description || p.name} */\n  readonly ${p.name}?: ${p.type} | undefined;`,
  );
  const vModelLines: string[] = [];
  if (model.primaryModelProp) {
    const primary = model.props.find((p) => p.name === model.primaryModelProp);
    const primaryType = primary?.type ?? 'unknown';
    vModelLines.push(`  readonly modelValue?: ${primaryType} | undefined;`);
    vModelLines.push(`  readonly 'onUpdate:modelValue'?: ((value: ${primaryType}) => void) | undefined;`);
  }
  for (const bindProp of model.bindableProps) {
    const prop = model.props.find((p) => p.name === bindProp);
    const propType = prop?.type ?? 'unknown';
    vModelLines.push(
      `  readonly ${JSON.stringify(`onUpdate:${bindProp}`)}?: ((value: ${propType}) => void) | undefined;`,
    );
  }
  const eventLines = model.events.map(
    (ev) =>
      `  readonly ${JSON.stringify(`on${ev.legacyReactPropName.slice(2)}`)}?: ((event: CustomEvent<${ev.detailType}>) => void) | undefined;`,
  );

  const allLines = [...propLines, ...vModelLines, ...eventLines];
  if (allLines.length === 0) {
    return `export type ${model.className}Props = Record<never, never>;`;
  }
  return `export interface ${model.className}Props {\n${allLines.join('\n')}\n}`;
}

function emitVueComponentWrapper(model: NormalizedComponentModel): string {
  const propNames = model.props.map((p) => JSON.stringify(p.name));
  const eventNames = model.events.map((e) => JSON.stringify(e.name));
  const emits = new Set<string>(model.events.map((e) => e.vueEmitName));
  if (model.primaryModelProp) {
    emits.add('update:modelValue');
  }
  for (const bindProp of model.bindableProps) {
    emits.add(`update:${bindProp}`);
  }

  const emitList = [...emits].map((e) => JSON.stringify(e)).join(', ');
  const bindablesList = model.bindableProps.map((b) => JSON.stringify(b)).join(', ');

  return `export const ${model.className}: DefineComponent<${model.className}Props> = createMethaneVueComponent<${model.className}Props>({
  name: ${JSON.stringify(model.className)},
  tagName: ${JSON.stringify(model.tagName)},
  propNames: [${propNames.join(', ')}],
  emits: [${emitList}],
  eventNames: [${eventNames.join(', ')}],
  primaryModelProp: ${model.primaryModelProp ? JSON.stringify(model.primaryModelProp) : 'null'},
  bindableProps: [${bindablesList}],
});`;
}

function emitVueComponentFile(model: NormalizedComponentModel): string {
  return `${BANNER}
import type { DefineComponent } from 'vue';
import { createMethaneVueComponent } from '../runtime.js';

${emitVuePropsInterface(model)}

${emitVueComponentWrapper(model)}

declare module 'vue' {
  export interface GlobalComponents {
    ${model.className}: DefineComponent<${model.className}Props>;
    ${JSON.stringify(model.tagName)}: DefineComponent<${model.className}Props>;
  }
}
`;
}

const VUE_RUNTIME_CONTENT = `${BANNER}
import { defineComponent, h, type DefineComponent, type PropType, type VNode } from 'vue';

export const METHANE_VUE_COMPILER_OPTIONS = {
  isCustomElement: (tag: string): boolean => tag.startsWith('mth-'),
} as const;

export function isMethaneVueTag(tag: string): boolean {
  return tag.startsWith('mth-');
}

export type VueBindProp = 'value' | 'checked' | 'open';

export interface MethaneVueComponentSpec {
  readonly name: string;
  readonly tagName: string;
  readonly propNames: ReadonlyArray<string>;
  readonly emits: ReadonlyArray<string>;
  readonly eventNames: ReadonlyArray<string>;
  readonly primaryModelProp: VueBindProp | null;
  readonly bindableProps: ReadonlyArray<VueBindProp>;
}

function extractVueBindValue(
  event: Event,
  bindProp: VueBindProp,
  primaryModelProp: VueBindProp | null,
): unknown {
  if (bindProp === 'open') {
    if (event.type === 'mth-open') return true;
    if (event.type === 'mth-close') return false;
  }
  const detail = (event as CustomEvent<Record<string, unknown> | undefined>).detail;
  if (detail && typeof detail === 'object') {
    return bindProp in detail ? detail[bindProp] : undefined;
  }
  if (bindProp === primaryModelProp) {
    const target = event.currentTarget as Record<string, unknown> | null;
    if (target && bindProp in target) {
      return target[bindProp];
    }
  }
  return undefined;
}

export function createMethaneVueComponent<Props extends object>(
  spec: MethaneVueComponentSpec,
): DefineComponent<Props> {
  const propsDef: Record<string, { type: PropType<unknown>; default: undefined }> = {};
  for (const propName of spec.propNames) {
    propsDef[propName] = { type: null as unknown as PropType<unknown>, default: undefined };
  }
  if (spec.primaryModelProp) {
    propsDef['modelValue'] = { type: null as unknown as PropType<unknown>, default: undefined };
  }

  return defineComponent({
    name: spec.name,
    inheritAttrs: false,
    props: propsDef,
    emits: [...spec.emits],
    setup(rawProps, { attrs, emit, slots }) {
      return () => {
        const propsRecord = rawProps as Record<string, unknown>;
        const vnodeProps: Record<string, unknown> = { ...attrs };

        for (const propName of spec.propNames) {
          const val = propsRecord[propName];
          if (val !== undefined) {
            vnodeProps[propName] = val;
          }
        }

        if (spec.primaryModelProp && propsRecord['modelValue'] !== undefined) {
          vnodeProps[spec.primaryModelProp] = propsRecord['modelValue'];
        }

        const syncBindings = (event: Event): void => {
          for (const bindProp of spec.bindableProps) {
            const next = extractVueBindValue(event, bindProp, spec.primaryModelProp);
            if (next !== undefined) {
              emit(\`update:\${bindProp}\`, next);
              if (spec.primaryModelProp === bindProp) {
                emit('update:modelValue', next);
              }
            }
          }
        };

        for (const eventName of spec.eventNames) {
          const key = \`on:\${eventName}\`;
          const prev = vnodeProps[key] as ((e: Event) => void) | undefined;
          vnodeProps[key] = (event: Event) => {
            syncBindings(event);
            emit(eventName, event);
            prev?.(event);
          };
        }

        if (spec.bindableProps.includes('value') || spec.bindableProps.includes('checked')) {
          for (const [key, nativeEvent] of [
            ['onInput', 'input'],
            ['onChange', 'change'],
          ] as const) {
            if (!spec.eventNames.includes(nativeEvent)) {
              const prev = vnodeProps[key] as ((e: Event) => void) | undefined;
              vnodeProps[key] = (event: Event) => {
                syncBindings(event);
                prev?.(event);
              };
            }
          }
        }

        const children: VNode[] = [];
        for (const slotFn of Object.values(slots)) {
          if (slotFn) {
            children.push(...slotFn());
          }
        }

        return h(spec.tagName, vnodeProps, children);
      };
    },
  }) as unknown as DefineComponent<Props>;
}
`;

export function generateVueFiles(
  models: ReadonlyArray<NormalizedComponentModel>,
): GeneratedFile[] {
  const files: GeneratedFile[] = [{ path: 'generated/runtime.ts', content: VUE_RUNTIME_CONTENT }];

  for (const model of models) {
    files.push({
      path: `generated/components/${model.tagName}.ts`,
      content: emitVueComponentFile(model),
    });
  }

  const componentExports = models
    .map((m) => `export * from './components/${m.tagName}.js';`)
    .join('\n');

  const indexContent = `${BANNER}
export { METHANE_VUE_COMPILER_OPTIONS, isMethaneVueTag } from './runtime.js';
${componentExports}
`;

  files.push({ path: 'generated/index.ts', content: indexContent });
  return files;
}
