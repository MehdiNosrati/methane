import type { GeneratedFile, NormalizedComponentModel } from '../types.js';
import { toPascalCase } from '../normalize.js';

function generateVsCodeCustomData(models: ReadonlyArray<NormalizedComponentModel>): string {
  const tags = models.map((m) => ({
    name: m.tagName,
    description: m.description || `Methane ${m.className} custom element`,
    attributes: m.props
      .filter((p) => p.attr !== null)
      .map((p) => ({
        name: p.attr as string,
        description: p.description || p.name,
      })),
  }));

  return JSON.stringify(
    {
      version: 1.1,
      tags,
    },
    null,
    2,
  ) + '\n';
}

function generateWebTypes(
  models: ReadonlyArray<NormalizedComponentModel>,
  packageVersion: string,
): string {
  const elements = models.map((m) => ({
    name: m.tagName,
    description: m.description || `Methane ${m.className} custom element`,
    attributes: m.props
      .filter((p) => p.attr !== null)
      .map((p) => ({
        name: p.attr as string,
        description: p.description || p.name,
        value: {
          kind: 'expression',
          type: p.type,
        },
        ...(p.defaultValue !== undefined ? { default: p.defaultValue } : {}),
      })),
    slots: m.slots.map((s) => ({
      name: s.name || 'default',
      description: s.description,
    })),
    events: m.events.map((e) => ({
      name: e.name,
      description: e.description,
    })),
    'css-parts': m.parts.map((p) => ({
      name: p.name,
      description: p.description,
    })),
    'css-properties': m.cssProperties.map((c) => ({
      name: c.name,
      description: c.description,
      ...(c.defaultValue !== undefined ? { default: c.defaultValue } : {}),
    })),
  }));

  return JSON.stringify(
    {
      $schema: 'https://raw.githubusercontent.com/JetBrains/web-types/master/schema/web-types.json',
      name: '@methane-ui/ui',
      version: packageVersion,
      'js-types-syntax': 'typescript',
      'description-markup': 'markdown',
      contributions: {
        html: {
          elements,
        },
      },
    },
    null,
    2,
  ) + '\n';
}

function generateDomMaps(models: ReadonlyArray<NormalizedComponentModel>): string {
  const banner = '// Generated by @methane-ui/wrapper-codegen. Do not edit by hand.';

  const interfaces = models
    .map((m) => {
      const propLines = m.props.map((p) => `  ${p.name}: ${p.type};`).join('\n');
      return `export interface ${m.elementInterfaceName} extends HTMLElement {\n${propLines}\n}`;
    })
    .join('\n\n');

  const tagMapEntries = models
    .map((m) => `    ${JSON.stringify(m.tagName)}: ${m.elementInterfaceName};`)
    .join('\n');

  const eventPairs = new Map<string, string>();
  for (const m of models) {
    for (const ev of m.events) {
      if (!eventPairs.has(ev.name)) {
        eventPairs.set(ev.name, `CustomEvent<${ev.detailType}>`);
      }
    }
  }

  const eventMapEntries = [...eventPairs.entries()]
    .map(([name, type]) => `    ${JSON.stringify(name)}: ${type};`)
    .join('\n');

  const eventTypeExports = [...eventPairs.entries()]
    .map(([name, type]) => `export type Mth${toPascalCase(name)}Event = ${type};`)
    .join('\n');

  return `${banner}

${interfaces}

${eventTypeExports}

declare global {
  interface HTMLElementTagNameMap {
${tagMapEntries}
  }

  interface HTMLElementEventMap {
${eventMapEntries}
  }
}

export {};
`;
}

export function generateIdeFiles(
  models: ReadonlyArray<NormalizedComponentModel>,
  packageVersion = '0.1.0',
): GeneratedFile[] {
  return [
    { path: 'vscode.html-custom-data.json', content: generateVsCodeCustomData(models) },
    { path: 'web-types.json', content: generateWebTypes(models, packageVersion) },
    { path: 'dom-maps.d.ts', content: generateDomMaps(models) },
  ];
}
