import type { GeneratedFile, NormalizedComponentModel } from '../types.js';

const BANNER = '// Generated by @methane-ui/wrapper-codegen. Do not edit by hand.';
const TAG_MAP_CHUNK_SIZE = 80;

function emitElementInterface(model: NormalizedComponentModel): string {
  if (model.props.length === 0) {
    return `export type ${model.elementInterfaceName} = HTMLElement;`;
  }
  const propLines = model.props.map(
    (p) => `  /** ${p.description || p.name} */\n  ${p.name}: ${p.type};`,
  );
  return `export interface ${model.elementInterfaceName} extends HTMLElement {\n${propLines.join('\n')}\n}`;
}

function emitEventHandlersInterface(model: NormalizedComponentModel): string {
  if (model.events.length === 0) {
    return `export type ${model.className}Events = Record<never, never>;`;
  }
  const lines = model.events.map(
    (ev) =>
      `  /** ${ev.description || ev.name} */\n  ${JSON.stringify(ev.reactPropName)}?: ((event: CustomEvent<${ev.detailType}>) => void) | undefined;`,
  );
  return `export interface ${model.className}Events {\n${lines.join('\n')}\n}`;
}

function emitReact19PropsInterface(model: NormalizedComponentModel): string {
  const customPropsDecl =
    model.props.length === 0
      ? `export type ${model.className}CustomProps = Record<never, never>;`
      : [
          `export interface ${model.className}CustomProps {`,
          ...model.props.map(
            (p) => `  /** ${p.description || p.name} */\n  ${p.name}?: ${p.type} | undefined;`,
          ),
          `}`,
        ].join('\n');

  return [
    `export type ${model.className}Props = Omit<`,
    `  React.DetailedHTMLProps<React.HTMLAttributes<${model.elementInterfaceName}>, ${model.elementInterfaceName}>,`,
    `  keyof ${model.className}CustomProps | keyof ${model.className}Events`,
    `> & ${model.className}CustomProps & ${model.className}Events;`,
    '',
    customPropsDecl,
  ].join('\n');
}

function emitReactComponentFile(model: NormalizedComponentModel): string {
  return `${BANNER}
import type React from 'react';

${emitElementInterface(model)}

${emitEventHandlersInterface(model)}

${emitReact19PropsInterface(model)}

declare module 'react' {
  // eslint-disable-next-line @typescript-eslint/no-namespace
  namespace JSX {
    interface IntrinsicElements {
      ${JSON.stringify(model.tagName)}: ${model.className}Props;
    }
  }
}
`;
}

function emitLegacyComponentFile(model: NormalizedComponentModel): string {
  const litReactImport =
    model.events.length > 0
      ? "import { createComponent, type EventName } from '@lit/react';"
      : "import { createComponent } from '@lit/react';";

  const eventEntries = model.events
    .map(
      (ev) =>
        `    ${ev.legacyReactPropName}: ${JSON.stringify(ev.name)} as EventName<CustomEvent<${ev.detailType}>>,`,
    )
    .join('\n');

  return `${BANNER}
import * as React from 'react';
${litReactImport}
import type { ${model.elementInterfaceName} } from '../components/${model.tagName}.js';
import { resolveElementClass } from '../legacy-runtime.js';

export const ${model.className} = /* @__PURE__ */ createComponent({
  react: React,
  tagName: ${JSON.stringify(model.tagName)},
  elementClass: resolveElementClass<${model.elementInterfaceName}>(${JSON.stringify(model.tagName)}),
  displayName: ${JSON.stringify(model.className)},
  events: {
${eventEntries}
  },
});
`;
}

export function generateReactFiles(
  models: ReadonlyArray<NormalizedComponentModel>,
): GeneratedFile[] {
  const files: GeneratedFile[] = [];

  for (const model of models) {
    files.push({
      path: `generated/components/${model.tagName}.ts`,
      content: emitReactComponentFile(model),
    });
  }

  const chunkNames: string[] = [];
  for (let i = 0; i < models.length; i += TAG_MAP_CHUNK_SIZE) {
    const chunk = models.slice(i, i + TAG_MAP_CHUNK_SIZE);
    const chunkIndex = Math.floor(i / TAG_MAP_CHUNK_SIZE);
    const chunkTypeName = `MethaneReactTagNameMapChunk${chunkIndex}`;
    chunkNames.push(chunkTypeName);

    const imports = chunk
      .map((m) => `import type { ${m.elementInterfaceName} } from './components/${m.tagName}.js';`)
      .join('\n');
    const entries = chunk
      .map((m) => `  ${JSON.stringify(m.tagName)}: ${m.elementInterfaceName};`)
      .join('\n');

    files.push({
      path: `generated/tag-map-${chunkIndex}.ts`,
      content: `${BANNER}\n${imports}\n\nexport interface ${chunkTypeName} {\n${entries}\n}\n`,
    });
  }

  const tagMapImports = chunkNames
    .map((name, idx) => `import type { ${name} } from './tag-map-${idx}.js';`)
    .join('\n');
  const tagMapUnion =
    chunkNames.length > 0 ? chunkNames.join(' & ') : 'Record<never, never>';

  const componentExports = models
    .map((m) => `export * from './components/${m.tagName}.js';`)
    .join('\n');

  const indexContent = `${BANNER}
${tagMapImports}

${componentExports}

export type MethaneReactTagNameMap = ${tagMapUnion};
`;

  files.push({ path: 'generated/index.ts', content: indexContent });

  const legacyRuntimeContent = `${BANNER}
export function resolveElementClass<T extends HTMLElement>(tagName: string): { new (): T } {
  const registered =
    typeof globalThis.customElements !== 'undefined'
      ? globalThis.customElements.get(tagName)
      : undefined;
  if (registered) {
    return registered as unknown as { new (): T };
  }
  const Base = (
    typeof globalThis.HTMLElement !== 'undefined' ? globalThis.HTMLElement : class {}
  ) as unknown as { new (): T };
  return class MethanePlaceholderElement extends Base {} as unknown as { new (): T };
}
`;
  files.push({ path: 'generated/legacy-runtime.ts', content: legacyRuntimeContent });

  for (const model of models) {
    files.push({
      path: `generated/legacy/${model.tagName}.ts`,
      content: emitLegacyComponentFile(model),
    });
  }

  const legacyExports = models
    .map((m) => `export { ${m.className} } from './legacy/${m.tagName}.js';`)
    .join('\n');
  files.push({
    path: 'generated/legacy.ts',
    content: `${BANNER}\n${legacyExports}\n`,
  });

  return files;
}
