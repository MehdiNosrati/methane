import type { GeneratedFile, NormalizedComponentModel } from '../types.js';

function emitAngularDirective(model: NormalizedComponentModel): string {
  const directiveName = `${model.className}Directive`;
  const inputNames = model.props.map((p) => JSON.stringify(p.name));
  const outputNames = model.events.map((e) => JSON.stringify(e.angularOutputName));

  const propFields = model.props
    .map((p) => `  @Input() ${p.name}?: ${p.type} | undefined;`)
    .join('\n');

  const eventFields = model.events
    .map(
      (ev) =>
        `  @Output(${JSON.stringify(ev.name)}) readonly ${ev.angularOutputName} = new EventEmitter<CustomEvent<${ev.detailType}>>();`,
    )
    .join('\n');

  const cvaImplements = model.formAssociated ? ' implements ControlValueAccessor, OnDestroy' : '';
  const providersLine = model.formAssociated
    ? `\n  providers: [{ provide: NG_VALUE_ACCESSOR, useExisting: forwardRef(() => ${directiveName}), multi: true }],`
    : '';

  const modelProp = model.primaryModelProp ?? 'value';
  const cvaBody = model.formAssociated
    ? `
  private readonly destroyController = new AbortController();
  private onChange: (value: unknown) => void = () => undefined;
  private onTouched: () => void = () => undefined;
  private lastValueEvent: Event | null = null;
  private lastBlurEvent: Event | null = null;

  constructor(@Inject(ElementRef) private readonly elementRef: ElementRef<HTMLElement & Record<string, unknown>>) {
    const el = this.elementRef?.nativeElement;
    if (el && typeof el.addEventListener === 'function') {
      const signal = this.destroyController.signal;
      for (const eventName of ['mth-input', 'mth-change', 'mth-select', 'input', 'change']) {
        el.addEventListener(eventName, (event) => this.handleValueEvent(event), { signal });
      }
      el.addEventListener('focusout', (event) => this.handleHostBlur(event), { signal });
    }
  }

  ngOnDestroy(): void {
    this.destroyController.abort();
  }

  writeValue(value: unknown): void {
    if (this.elementRef?.nativeElement) {
      this.elementRef.nativeElement[${JSON.stringify(modelProp)}] = value;
    }
  }

  registerOnChange(fn: (value: unknown) => void): void {
    this.onChange = fn;
  }

  registerOnTouched(fn: () => void): void {
    this.onTouched = fn;
  }

  setDisabledState(isDisabled: boolean): void {
    if (this.elementRef?.nativeElement) {
      this.elementRef.nativeElement['disabled'] = isDisabled;
    }
  }

  @HostListener('mth-input', ['$event'])
  @HostListener('mth-change', ['$event'])
  @HostListener('mth-select', ['$event'])
  @HostListener('input', ['$event'])
  @HostListener('change', ['$event'])
  handleValueEvent(event: Event): void {
    if (event === this.lastValueEvent) return;
    this.lastValueEvent = event;
    const next = extractAngularModelValue(event, ${JSON.stringify(modelProp)}, this.elementRef?.nativeElement);
    if (next !== undefined) {
      this.onChange(next);
    }
  }

  @HostListener('focusout', ['$event'])
  handleHostBlur(event?: Event): void {
    if (event) {
      if (event === this.lastBlurEvent) return;
      this.lastBlurEvent = event;
    }
    this.onTouched();
  }`
    : '';

  return `@Directive({
  selector: ${JSON.stringify(model.tagName)},
  standalone: true,
  inputs: [${inputNames.join(', ')}],
  outputs: [${outputNames.join(', ')}],${providersLine}
})
export class ${directiveName}${cvaImplements} {
${[propFields, eventFields].filter(Boolean).join('\n')}${cvaBody}
}`;
}

export function generateAngularFiles(
  models: ReadonlyArray<NormalizedComponentModel>,
): GeneratedFile[] {
  const banner = '// Generated by @methane/wrapper-codegen. Do not edit by hand.';
  const directives = models.map(emitAngularDirective).join('\n\n');
  const directiveNames = models.map((m) => `  ${m.className}Directive,`).join('\n');

  const indexContent = `${banner}
import {
  Directive,
  ElementRef,
  EventEmitter,
  HostListener,
  Inject,
  Input,
  Output,
  forwardRef,
  type OnDestroy,
} from '@angular/core';
import { NG_VALUE_ACCESSOR, type ControlValueAccessor } from '@angular/forms';

function extractAngularModelValue(
  event: Event,
  modelProp: string,
  host?: (HTMLElement & Record<string, unknown>) | null,
): unknown {
  const detail = (event as CustomEvent<Record<string, unknown> | undefined>).detail;
  if (detail && typeof detail === 'object' && modelProp in detail) {
    return detail[modelProp];
  }
  const target = (event.currentTarget ?? host) as Record<string, unknown> | null | undefined;
  return target ? target[modelProp] : undefined;
}

${directives}

export const METHANE_ANGULAR_DIRECTIVES = [
${directiveNames}
] as const;
`;

  return [{ path: 'index.ts', content: indexContent }];
}
