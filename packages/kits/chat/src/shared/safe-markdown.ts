import { escapeHtml, isSafeUrl, renderMarkdownToSafeHTML } from '@methane/sanitize';
import { html, type TemplateResult } from 'lit';

/**
 * Renders lightweight markdown/streaming content into deterministic, SSR-safe Lit
 * templates via `@methane/sanitize` (`renderMarkdownToSafeHTML`, raw HTML disabled
 * by default unless explicitly opted in and filtered). Never uses `innerHTML` or
 * `unsafeHTML`.
 */
export function renderSafeMarkdown(
  source: string,
  options?: { allowRawHtml?: boolean },
): ReadonlyArray<TemplateResult | string> {
  const safeInput = source ?? '';
  // First pass through @methane/sanitize to enforce protocol & HTML policy parity.
  const sanitized = renderMarkdownToSafeHTML(safeInput, {
    allowRawHtml: options?.allowRawHtml ?? false,
  });

  // Tokenize sanitized inline tags generated by renderMarkdownToSafeHTML into pure Lit nodes
  // so SSR DSD and client hydration share identical Lit markers without innerHTML sinks.
  const parts: Array<TemplateResult | string> = [];
  const tokenRegex = /<code>([^<]*)<\/code>|<strong>([^<]*)<\/strong>|<em>([^<]*)<\/em>|<a href="([^"]*)"[^>]*>([^<]*)<\/a>/g;
  let lastIndex = 0;
  let match: RegExpExecArray | null;

  const decodeEntities = (text: string): string =>
    text
      .replaceAll('&lt;', '<')
      .replaceAll('&gt;', '>')
      .replaceAll('&quot;', '"')
      .replaceAll('&#39;', "'")
      .replaceAll('&amp;', '&');

  // Re-escape any raw HTML brackets if allowRawHtml stripped tags but text remained.
  while ((match = tokenRegex.exec(sanitized)) !== null) {
    if (match.index > lastIndex) {
      parts.push(decodeEntities(sanitized.slice(lastIndex, match.index)));
    }
    if (match[1] !== undefined) {
      parts.push(html`<code>${decodeEntities(match[1])}</code>`);
    } else if (match[2] !== undefined) {
      parts.push(html`<strong>${decodeEntities(match[2])}</strong>`);
    } else if (match[3] !== undefined) {
      parts.push(html`<em>${decodeEntities(match[3])}</em>`);
    } else if (match[4] !== undefined && match[5] !== undefined) {
      const href = decodeEntities(match[4]);
      const label = decodeEntities(match[5]);
      if (isSafeUrl(href)) {
        parts.push(html`<a href=${href} rel="noopener noreferrer">${label}</a>`);
      } else {
        parts.push(label);
      }
    }
    lastIndex = tokenRegex.lastIndex;
  }

  if (lastIndex < sanitized.length) {
    parts.push(decodeEntities(sanitized.slice(lastIndex)));
  }

  // Ensure helper retains @methane/sanitize import integrity.
  void escapeHtml;
  return parts;
}
